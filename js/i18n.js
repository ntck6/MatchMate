  const LOCALES = { en: 'en-GB', vi: 'vi-VN' };
  let current = 'en';

  function t(key, vars) {
    const table = STRINGS[current] || STRINGS.en;
    let s = table[key];
    if (s == null) s = STRINGS.en[key];
    if (s == null) return key;
    if (vars) {
      s = s.replace(/\{(\w+)\}/g, function (_, k) {
        return vars[k] != null ? vars[k] : '';
      });
    }
    return s;
  }

  function apply(root) {
    const scope = root || document;
    scope.querySelectorAll('[data-i18n]').forEach(function (el) {
      el.textContent = t(el.getAttribute('data-i18n'));
    });
    scope.querySelectorAll('[data-i18n-attr]').forEach(function (el) {
      el.getAttribute('data-i18n-attr').split(';').forEach(function (pair) {
        const parts = pair.split(':');
        if (parts.length === 2) el.setAttribute(parts[0].trim(), t(parts[1].trim()));
      });
    });
    const pg = document.body && document.body.getAttribute('data-page');
    document.title = t(pg ? 'meta.title.' + pg : 'meta.title');
    document.documentElement.lang = current;
  }

  return {
    t: t,
    apply: apply,
    get lang() { return current; },
    set lang(v) { current = STRINGS[v] ? v : 'en'; },
    get locale() { return LOCALES[current]; },
    // Pick the right side of a { en, vi } object
    pick: function (obj) { return obj ? (obj[current] != null ? obj[current] : obj.en) : ''; }
  };
